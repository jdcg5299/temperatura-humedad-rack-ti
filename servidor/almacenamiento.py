"""Doble almacenamiento obligatorio: base de datos + CSV (principio 3 de la constitución).

- Base de datos (SQLite o PostgreSQL): el histórico, lo usa el GET.
- lecturas.csv: evidencia fácil de abrir y mostrar.

Las dos escrituras comparten un lock porque el CSV no se protege solo:
dos peticiones simultáneas podrían intercalar medio renglón y corromperlo.

Motor de la base de datos: si existe la variable de entorno DATABASE_URL
(formato postgresql://usuario:clave@host:5432/nombre) se usa PostgreSQL
con psycopg 3; si no existe, se usa SQLite como siempre. La API pública
(inicializar, guardar, obtener_ultimas) es idéntica para los dos motores,
por eso app.py y el contrato HTTP no cambian.
"""

import csv
import os
import sqlite3
import threading
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

# Los archivos viven al lado de este código (en la VM: /vagrant/servidor/).
RUTA_DB = Path(__file__).with_name("datos.db")
RUTA_CSV = Path(__file__).with_name("lecturas.csv")
# Configuración local opcional (copiada de .env.example); nunca va al repositorio.
RUTA_ENV = Path(__file__).with_name(".env")

ENCABEZADOS_CSV = ("fecha", "dispositivo", "temperatura", "humedad", "estado")

_lock = threading.Lock()

# Se llena en inicializar(): la URL de PostgreSQL ya validada, o None para SQLite.
_url_postgres: str | None = None

# Mismo esquema para los dos motores; solo cambia el id autoincremental:
# SQLite usa AUTOINCREMENT y PostgreSQL usa IDENTITY (su equivalente estándar).
SQL_CREAR_TABLA = """
    CREATE TABLE IF NOT EXISTS lecturas (
        {id},
        dispositivo TEXT NOT NULL,
        temperatura REAL NOT NULL,
        humedad REAL NOT NULL,
        fecha TEXT NOT NULL,
        estado TEXT NOT NULL
    )
"""
ID_SQLITE = "id INTEGER PRIMARY KEY AUTOINCREMENT"
ID_POSTGRES = "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"


def _cargar_env() -> None:
    """Lee servidor/.env si existe, sin sobrescribir variables ya definidas.

    Así la clave de PostgreSQL no vive en el código ni en el repositorio
    (principio 6 de la constitución), y el entorno (systemd, un export)
    siempre gana sobre el archivo.
    """
    if not RUTA_ENV.exists():
        return
    for linea in RUTA_ENV.read_text(encoding="utf-8").splitlines():
        linea = linea.strip()
        # Formato simple NOMBRE=VALOR; se ignoran comentarios y líneas vacías.
        if not linea or linea.startswith("#") or "=" not in linea:
            continue
        nombre, valor = linea.split("=", 1)
        nombre = nombre.strip()
        if nombre and nombre not in os.environ:
            os.environ[nombre] = valor.strip()


def _leer_url_postgres() -> str | None:
    """Devuelve la URL de PostgreSQL, o None si toca usar SQLite."""
    _cargar_env()
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url:
        return None
    if not url.startswith("postgresql://"):
        # Fallar aquí con mensaje claro evita un error críptico de conexión.
        raise SystemExit(
            "DATABASE_URL debe tener el formato "
            "postgresql://usuario:clave@host:5432/nombre"
        )
    return url


def inicializar() -> None:
    """Crea la tabla si no existe. Se llama una vez al arrancar el servidor."""
    global _url_postgres
    _url_postgres = _leer_url_postgres()
    if _url_postgres is None:
        _crear_tabla_sqlite()
    else:
        _crear_tabla_postgres()


def guardar(lectura: dict, fecha: str, estado: str) -> int:
    """Guarda la lectura en la base de datos y en el CSV. Devuelve el id."""
    with _lock:
        if _url_postgres is None:
            id_ = _insertar_sqlite(lectura, fecha, estado)
        else:
            id_ = _insertar_postgres(lectura, fecha, estado)
        _insertar_csv(lectura, fecha, estado)
    return id_


def obtener_ultimas(limite: int) -> list[dict]:
    """Las últimas lecturas, de la más reciente a la más vieja."""
    if _url_postgres is None:
        return _obtener_ultimas_sqlite(limite)
    return _obtener_ultimas_postgres(limite)


def _crear_tabla_sqlite() -> None:
    con = sqlite3.connect(RUTA_DB)
    try:
        con.execute(SQL_CREAR_TABLA.format(id=ID_SQLITE))
        con.commit()
    finally:
        con.close()


def _crear_tabla_postgres() -> None:
    try:
        with _conectar_postgres() as con:
            con.execute(SQL_CREAR_TABLA.format(id=ID_POSTGRES))
    except psycopg.OperationalError as exc:
        # Fallar al arrancar (y no en la primera lectura) hace el problema
        # obvio de inmediato. El mensaje no repite la URL completa para no
        # filtrar la clave a los logs.
        raise SystemExit(
            "No se pudo conectar a PostgreSQL. Revise DATABASE_URL "
            "(host, puerto, usuario, clave) y que el servidor este en marcha. "
            f"Detalle: {exc}"
        ) from exc


def _conectar_postgres():
    # Una conexión por operación: simple y seguro entre hilos (el costo no
    # importa aquí: el DHT11 envía una lectura cada 10 segundos).
    # dict_row hace que cada fila ya venga como dict, igual que en SQLite.
    return psycopg.connect(_url_postgres, row_factory=dict_row)


def _insertar_sqlite(lectura: dict, fecha: str, estado: str) -> int:
    con = sqlite3.connect(RUTA_DB)
    try:
        cursor = con.execute(
            """
            INSERT INTO lecturas (dispositivo, temperatura, humedad, fecha, estado)
            VALUES (?, ?, ?, ?, ?)
            """,
            (
                lectura["dispositivo"],
                lectura["temperatura"],
                lectura["humedad"],
                fecha,
                estado,
            ),
        )
        con.commit()
        return cursor.lastrowid
    finally:
        con.close()


def _insertar_postgres(lectura: dict, fecha: str, estado: str) -> int:
    # Ojo con las diferencias entre motores: PostgreSQL usa %s (no ?)
    # y no tiene lastrowid; se pide el id con RETURNING.
    with _conectar_postgres() as con:
        fila = con.execute(
            """
            INSERT INTO lecturas (dispositivo, temperatura, humedad, fecha, estado)
            VALUES (%s, %s, %s, %s, %s)
            RETURNING id
            """,
            (
                lectura["dispositivo"],
                lectura["temperatura"],
                lectura["humedad"],
                fecha,
                estado,
            ),
        ).fetchone()
        return fila["id"]


def _obtener_ultimas_sqlite(limite: int) -> list[dict]:
    con = sqlite3.connect(RUTA_DB)
    try:
        con.row_factory = sqlite3.Row
        filas = con.execute(
            """
            SELECT id, dispositivo, temperatura, humedad, fecha, estado
            FROM lecturas
            ORDER BY id DESC
            LIMIT ?
            """,
            (limite,),
        ).fetchall()
        return [dict(fila) for fila in filas]
    finally:
        con.close()


def _obtener_ultimas_postgres(limite: int) -> list[dict]:
    with _conectar_postgres() as con:
        filas = con.execute(
            """
            SELECT id, dispositivo, temperatura, humedad, fecha, estado
            FROM lecturas
            ORDER BY id DESC
            LIMIT %s
            """,
            (limite,),
        ).fetchall()
        return filas


def _insertar_csv(lectura: dict, fecha: str, estado: str) -> None:
    # Se añade el encabezado solo la primera vez (archivo nuevo o vacío).
    vacio = not RUTA_CSV.exists() or RUTA_CSV.stat().st_size == 0
    # newline="" es lo que pide el módulo csv para no duplicar saltos de línea.
    with RUTA_CSV.open("a", newline="", encoding="utf-8") as archivo:
        escritor = csv.writer(archivo)
        if vacio:
            escritor.writerow(ENCABEZADOS_CSV)
        escritor.writerow(
            (
                fecha,
                lectura["dispositivo"],
                lectura["temperatura"],
                lectura["humedad"],
                estado,
            )
        )
